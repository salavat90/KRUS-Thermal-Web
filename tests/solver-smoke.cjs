run('default closed water conserves power',()=>{let m=calc();assert.ok(Math.abs(m.power-60)<1e-8);assert.ok(Math.abs(m.residual)<0.5,'energy residual '+m.residual);assert.ok(Number.isFinite(m.waterMean));});
